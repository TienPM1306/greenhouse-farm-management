// Trả về chuỗi SVG.
//  • Tiền tố "duo:" → Phosphor Duotone (fill 2 lớp, viewBox 256).
//  • Còn lại → Lucide stroke (viewBox 24). opts.stroke đổi độ dày.
// opts.size đổi cỡ (mặc định 1em theo font).
export function icon(name, { size = "1em", stroke = 2, cls = "" } = {}) {
  if (name.startsWith("duo:")) {
    const d = DUOTONE[name.slice(4)];
    if (!d) return "";
    return `<svg class="icon icon--duo ${cls}" width="${size}" height="${size}" viewBox="0 0 256 256" fill="currentColor" aria-hidden="true">${d.bg}${d.fg}</svg>`;
  }
  const d = PATHS[name];
  if (!d) return "";
  return `<svg class="icon ${cls}" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="${stroke}" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${d}</svg>`;
}

// Tạo phần tử SVG (khi cần append trực tiếp).
export function iconEl(name, opts) {
  const wrap = document.createElement("span");
  wrap.className = "icon-wrap";
  wrap.innerHTML = icon(name, opts);
  return wrap.firstChild;
}
